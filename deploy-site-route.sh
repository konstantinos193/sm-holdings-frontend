#!/bin/bash
################################################################################
# Point Traefik's smholdings.gr routes at one colour of the site, and prove
# Traefik took it -- the site's form of the API's deploy-traefik-route.sh.
#
#   bash deploy-site-route.sh <green|blue>
#
# Called by deploy-site.sh after the new colour's health check passes. Exits
# non-zero, leaving the previous file in force, when Traefik does not confirm
# the change; the deploy then aborts before it stops the old colour.
#
# What it writes, /etc/stefanos/traefik/dynamic/web.yml, is hot-reloaded by
# the file provider: no reload, no restart, and Traefik's API (loopback only)
# reports what was actually loaded -- a router with a broken rule or a missing
# middleware shows up there as disabled and nowhere else.
#
# TLS_MODE (default: auto):
#   auto  certResolver only when SITE_DOMAIN already resolves to this box.
#         Before the Vercel DNS flip it writes `tls: {}` instead -- Traefik
#         would otherwise hammer Let's Encrypt with HTTP-01 challenges that
#         still land on Vercel's edge and burn the failed-validation budget.
#   on    always certResolver (the DNS flip is done, or forced).
#   off   never certResolver (staging before the flip; Traefik serves its
#         default cert on this host until the flip).
################################################################################

set -euo pipefail

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

if [ "$#" -ne 1 ] || { [ "$1" != green ] && [ "$1" != blue ]; }; then
    echo "Usage: $0 <green|blue>" >&2
    exit 2
fi
COLOR=$1
CONTAINER=site-$COLOR

TRAEFIK_DIR=${TRAEFIK_DIR:-/etc/stefanos/traefik}
TRAEFIK_API=${TRAEFIK_API:-http://127.0.0.1:8099}
TRAEFIK_HTTPS_PORT=${TRAEFIK_HTTPS_PORT:-443}
SITE_DOMAIN=${SITE_DOMAIN:-smholdings.gr}
WWW_DOMAIN=${WWW_DOMAIN:-www.$SITE_DOMAIN}
APP_PORT=${APP_PORT:-3000}
PUBLIC_IP=${PUBLIC_IP:-}
TLS_MODE=${TLS_MODE:-auto}

DYNAMIC_DIR="$TRAEFIK_DIR/dynamic"
TARGET="$DYNAMIC_DIR/web.yml"
UPSTREAM="http://$CONTAINER:$APP_PORT"

mkdir -p "$DYNAMIC_DIR"

# ---------------------------------------------------------------------------
# Does the domain already resolve to this box? getent, not dig -- dnsutils is
# not installed. PUBLIC_IP overrides egress detection when it lies.
# ---------------------------------------------------------------------------
resolves_here() {
    local ip mine
    ip=$(getent ahostsv4 "$SITE_DOMAIN" 2>/dev/null | awk 'NR==1 {print $1}')
    [ -n "$ip" ] || return 1
    mine=${PUBLIC_IP:-$(curl -4 -sf --max-time 5 https://api.ipify.org 2>/dev/null \
        || curl -4 -sf --max-time 5 https://ifconfig.me 2>/dev/null || true)}
    [ -n "$mine" ] && [ "$ip" = "$mine" ]
}

case "$TLS_MODE" in
    on)  TLS_BLOCK=$'tls:\n        certResolver: letsencrypt' ;;
    off) TLS_BLOCK='tls: {}' ;;
    auto)
        if resolves_here; then
            TLS_BLOCK=$'tls:\n        certResolver: letsencrypt'
            echo -e "${GREEN}  $SITE_DOMAIN resolves here -- certResolver letsencrypt${NC}"
        else
            TLS_BLOCK='tls: {}'
            echo -e "${YELLOW}  $SITE_DOMAIN does not resolve here yet -- tls:{} (no ACME burn)${NC}"
            echo -e "${YELLOW}  Flip the Vercel DNS A record, then re-run this script.${NC}"
        fi
        ;;
    *) echo "TLS_MODE must be auto|on|off" >&2; exit 2 ;;
esac

TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT

cat > "$TMP" <<EOF
# Generated by stefanos-frontend/deploy-site-route.sh on $(date -u '+%Y-%m-%d %H:%M:%S UTC').
# DO NOT EDIT BY HAND -- the next deploy overwrites it. Change the script.
#
# Live colour: $CONTAINER

http:
  middlewares:
    # Public marketing site: looser than the API -- real visitors plus the
    # crawler population Google sends at a real estate domain. Per source IP.
    smh-web-ratelimit:
      rateLimit:
        average: 60
        burst: 120

  services:
    # Traefik keeps a keepalive pool to the app by default and passes the
    # client's Host header through (the app reads it for its www->apex 301).
    # healthCheck pulls a wedged colour out of rotation on its own; the probe
    # hits a static asset because / 308s to a locale path.
    smh-site:
      loadBalancer:
        servers:
          - url: "$UPSTREAM"
        healthCheck:
          path: /og-image.png
          interval: 10s
          timeout: 3s

  routers:
    # Let's Encrypt's HTTP-01 on 443 too: once the DNS flips, challenges on
    # port 80 are redirected to websecure by the static config and answered
    # here. Priority above the site's so the path never hits Next.
    smh-acme:
      entryPoints: [websecure]
      rule: "Host(\`$SITE_DOMAIN\`) && PathPrefix(\`/.well-known/acme-challenge/\`)"
      priority: 2000
      service: acme-http@internal

    # The site. One router covers apex and www so the ACME order is a single
    # SAN certificate; the app itself 301s www -> apex (host-header redirect
    # in next.config.js, unchanged from Vercel).
    smh-web:
      entryPoints: [websecure]
      rule: "Host(\`$SITE_DOMAIN\`) || Host(\`$WWW_DOMAIN\`)"
      priority: 100
      middlewares: [smh-web-ratelimit, st-inflight@file, st-compress@file]
      service: smh-site
      $TLS_BLOCK
EOF

# The previous file, kept until this one is proven: if Traefik does not load
# the new routes it goes back, so a failed deploy leaves the old colour
# serving rather than a route to nowhere.
cp -p "$TARGET" "$TARGET.prev" 2>/dev/null || true
restore_previous() {
    if [ -f "$TARGET.prev" ]; then
        mv "$TARGET.prev" "$TARGET"
        echo -e "${YELLOW}  Previous $TARGET restored${NC}"
    fi
}

# Atomic: Traefik watches the directory and must never read a half-written
# file. The .tmp/.prev extensions are ones the file provider ignores.
install -m 0644 "$TMP" "$TARGET.tmp"
mv "$TARGET.tmp" "$TARGET"
echo -e "${GREEN}  ✓ $TARGET written ($CONTAINER via $UPSTREAM)${NC}"

if [ "${TRAEFIK_ROUTE_VERIFY:-1}" = 0 ]; then
    exit 0
fi

traefik_has_loaded() {
    local svc router
    svc=$(curl -sf --max-time 3 "$TRAEFIK_API/api/http/services/smh-site@file" 2>/dev/null) || return 1
    router=$(curl -sf --max-time 3 "$TRAEFIK_API/api/http/routers/smh-web@file" 2>/dev/null) || return 1
    echo "$svc" | grep -qF "\"url\":\"$UPSTREAM\"" || return 1
    echo "$router" | grep -q '"status":"enabled"' || return 1
}

loaded=0
for _ in $(seq 1 20); do
    if traefik_has_loaded; then
        loaded=1
        break
    fi
    sleep 1
done
if [ "$loaded" -ne 1 ]; then
    echo -e "${RED}✗ Traefik did not load web.yml with $UPSTREAM within 20s${NC}"
    echo -e "${RED}  Check: tail -20 $TRAEFIK_DIR/logs/traefik.log${NC}"
    tail -5 "$TRAEFIK_DIR/logs/traefik.log" 2>&1 | sed 's/^/    /' || true
    restore_previous
    exit 1
fi

# Then a real request through it: 502/504/000 mean nothing answered;
# anything else (a 404 on a missing page included) means the app did.
# --resolve pins the TLS server name to loopback; -k because the cert may
# legitimately not exist yet (pre-DNS-flip staging or ACME still working).
status=""
for _ in 1 2 3 4 5; do
    status=$(curl -sk -o /dev/null -w '%{http_code}' --max-time 15 \
        --resolve "$SITE_DOMAIN:$TRAEFIK_HTTPS_PORT:127.0.0.1" \
        "https://$SITE_DOMAIN:$TRAEFIK_HTTPS_PORT/en" 2>/dev/null || true)
    case "$status" in
        502|503|504|000|"") sleep 2 ;;
        *)
            echo -e "${GREEN}  ✓ Traefik serves $SITE_DOMAIN from $CONTAINER (HTTP $status)${NC}"
            rm -f "$TARGET.prev"
            break
            ;;
    esac
done
case "$status" in
    502|503|504|000|"")
        echo -e "${RED}✗ Traefik loaded the route but the site does not answer through it (last: ${status:-none})${NC}"
        restore_previous
        exit 1
        ;;
esac

# With certResolver on a freshly-flipped domain, ACME issuance is async.
# Wait it out so a deploy reports the truth, but do not roll back the route:
# the default cert keeps serving while Traefik retries, which beats a route
# to nowhere.
if [ "$TLS_BLOCK" != 'tls: {}' ]; then
    issued=0
    for _ in $(seq 1 60); do
        if grep -q "\"main\": *\"$SITE_DOMAIN\"\|\"main\":\"$SITE_DOMAIN\"" "$TRAEFIK_DIR/acme/acme.json" 2>/dev/null; then
            issued=1
            break
        fi
        sleep 2
    done
    if [ "$issued" -eq 1 ]; then
        echo -e "${GREEN}  ✓ Let's Encrypt certificate issued for $SITE_DOMAIN (+$WWW_DOMAIN)${NC}"
    else
        echo -e "${YELLOW}  ! ACME has not issued $SITE_DOMAIN within 120s -- Traefik keeps retrying.${NC}"
        echo -e "${YELLOW}    tail -f $TRAEFIK_DIR/logs/traefik.log | grep -i acme${NC}"
    fi
fi
